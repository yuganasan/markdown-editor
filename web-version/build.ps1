# Builds MarkdownEditor.exe from MarkdownEditor.cs + markdown-editor.html.
# Uses the C# compiler that ships with Windows - nothing to install.
# Re-run this after editing markdown-editor.html to fold the changes into the exe.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

$htmlPath = Join-Path $root "markdown-editor.html"
$csPath   = Join-Path $root "MarkdownEditor.cs"
$genPath  = Join-Path $root "HtmlSource.cs"
$icoPath  = Join-Path $root "MarkdownEditor.ico"
$exePath  = Join-Path $root "MarkdownEditor.exe"

foreach ($f in @($htmlPath, $csPath)) {
    if (-not (Test-Path $f)) { throw "Missing required file: $f" }
}

# ---- 1. embed the editor page as base64 chunks -----------------------------
Write-Host "Embedding markdown-editor.html..."
$bytes = [System.IO.File]::ReadAllBytes($htmlPath)
$b64 = [Convert]::ToBase64String($bytes)
$chunks = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $b64.Length; $i += 2000) {
    $len = [Math]::Min(2000, $b64.Length - $i)
    $chunks.Add('        "' + $b64.Substring($i, $len) + '"')
}
$src = @(
    "// Generated by build.ps1 - do not edit.",
    "using System;",
    "using System.Text;",
    "",
    "static class HtmlSource",
    "{",
    "    static readonly string[] P = new string[] {",
    ($chunks -join ",`r`n"),
    "    };",
    "    public static string Text",
    "    {",
    "        get { return new UTF8Encoding(false).GetString(Convert.FromBase64String(string.Concat(P))); }",
    "    }",
    "}"
) -join "`r`n"
[System.IO.File]::WriteAllText($genPath, $src, (New-Object System.Text.UTF8Encoding($false)))

# ---- 2. icon ---------------------------------------------------------------
if (-not (Test-Path $icoPath)) {
    Write-Host "Drawing icon..."
    Add-Type -AssemblyName System.Drawing
    $pngs = @()
    foreach ($size in 16, 32, 48, 256) {
        $bmp = New-Object System.Drawing.Bitmap($size, $size)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.SmoothingMode = "AntiAlias"
        $g.TextRenderingHint = "AntiAliasGridFit"
        $g.Clear([System.Drawing.Color]::Transparent)

        $r = [Math]::Max(2, [int]($size * 0.18))
        $pad = [Math]::Max(0, [int]($size * 0.03))
        $w = $size - 1 - ($pad * 2)
        $path = New-Object System.Drawing.Drawing2D.GraphicsPath
        $path.AddArc($pad, $pad, $r * 2, $r * 2, 180, 90)
        $path.AddArc($pad + $w - $r * 2, $pad, $r * 2, $r * 2, 270, 90)
        $path.AddArc($pad + $w - $r * 2, $pad + $w - $r * 2, $r * 2, $r * 2, 0, 90)
        $path.AddArc($pad, $pad + $w - $r * 2, $r * 2, $r * 2, 90, 90)
        $path.CloseFigure()
        $brush = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(37, 99, 235))
        $g.FillPath($brush, $path)

        # white down-arrow: reads as "markdown" at every size, unlike a letter
        $cx = $size / 2.0
        $aw = $size * 0.30
        $stemW = [Math]::Max(2.0, $size * 0.11)
        $top = $size * 0.24
        $shoulder = $size * 0.52
        $bottom = $size * 0.76
        $pts = @(
            (New-Object System.Drawing.PointF(($cx - $stemW / 2), $top)),
            (New-Object System.Drawing.PointF(($cx + $stemW / 2), $top)),
            (New-Object System.Drawing.PointF(($cx + $stemW / 2), $shoulder)),
            (New-Object System.Drawing.PointF(($cx + $aw / 2), $shoulder)),
            (New-Object System.Drawing.PointF($cx, $bottom)),
            (New-Object System.Drawing.PointF(($cx - $aw / 2), $shoulder)),
            (New-Object System.Drawing.PointF(($cx - $stemW / 2), $shoulder))
        )
        $g.FillPolygon([System.Drawing.Brushes]::White, [System.Drawing.PointF[]]$pts)

        $g.Dispose()
        $ms = New-Object System.IO.MemoryStream
        $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
        $bmp.Dispose()
        $pngs += , @{ size = $size; data = $ms.ToArray() }
        $ms.Dispose()
    }

    $ico = New-Object System.IO.MemoryStream
    $bw = New-Object System.IO.BinaryWriter($ico)
    $bw.Write([UInt16]0); $bw.Write([UInt16]1); $bw.Write([UInt16]$pngs.Count)
    $offset = 6 + (16 * $pngs.Count)
    foreach ($p in $pngs) {
        $dim = if ($p.size -ge 256) { 0 } else { $p.size }
        $bw.Write([Byte]$dim); $bw.Write([Byte]$dim)
        $bw.Write([Byte]0); $bw.Write([Byte]0)
        $bw.Write([UInt16]1); $bw.Write([UInt16]32)
        $bw.Write([UInt32]$p.data.Length); $bw.Write([UInt32]$offset)
        $offset += $p.data.Length
    }
    foreach ($p in $pngs) { $bw.Write($p.data) }
    $bw.Flush()
    [System.IO.File]::WriteAllBytes($icoPath, $ico.ToArray())
    $bw.Dispose()
}

# ---- 3. compile ------------------------------------------------------------
$csc = Join-Path $env:WINDIR "Microsoft.NET\Framework64\v4.0.30319\csc.exe"
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR "Microsoft.NET\Framework\v4.0.30319\csc.exe" }
if (-not (Test-Path $csc)) { throw "No C# compiler found under $env:WINDIR\Microsoft.NET" }

Write-Host "Compiling..."
$args = @(
    "/nologo", "/target:winexe", "/optimize+", "/platform:anycpu",
    "/out:$exePath", "/win32icon:$icoPath",
    "/reference:System.dll", "/reference:System.Drawing.dll",
    "/reference:System.Windows.Forms.dll",
    $csPath, $genPath
)
& $csc $args
if ($LASTEXITCODE -ne 0) { throw "Compile failed (exit $LASTEXITCODE)" }

$kb = [Math]::Round((Get-Item $exePath).Length / 1KB, 1)
Write-Host "Built $exePath ($kb KB)" -ForegroundColor Green
